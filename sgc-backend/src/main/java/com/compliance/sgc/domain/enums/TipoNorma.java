package com.compliance.sgc.domain.enums;

/**
 * Tipo de norma legal.
 *
 * @author Arquiteto de Soluções Sênior
 * @version 1.0
 * @since 2025-11-14
 */
public enum TipoNorma {
  /**
   * Lei federal, estadual ou municipal.
   */
  LEI,

  /**
   * Decreto regulamentador.
   */
  DECRETO,

  /**
   * Resolução de órgãos colegiados.
   */
  RESOLUCAO,

  /**
   * Portaria ministerial ou de órgãos.
   */
  PORTARIA,

  /**
   * Instrução Normativa.
   */
  INSTRUCAO_NORMATIVA
}
