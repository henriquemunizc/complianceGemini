package com.compliance.sgc.domain.enums;

/**
 * Periodicidade de uma obrigação.
 *
 * @author Arquiteto de Soluções Sênior
 * @version 1.0
 * @since 2025-11-14
 */
public enum Periodicidade {
  /**
   * Obrigação única (não recorrente).
   */
  UNICA,

  /**
   * Obrigação mensal.
   */
  MENSAL,

  /**
   * Obrigação trimestral.
   */
  TRIMESTRAL,

  /**
   * Obrigação semestral.
   */
  SEMESTRAL,

  /**
   * Obrigação anual.
   */
  ANUAL
}
